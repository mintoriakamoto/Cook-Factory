"use strict";
/**
 * roadmap-index: the generated regions of `.planning/ROADMAP.md`.
 *
 * PURE locator + renderer for the phase index under `## Phases` and the
 * progress section under `## Progress` (Phase 14.1, v1.14 Fleet Mode). Mirrors
 * `milestone-manifest.cts` in shape, with one difference that is the whole
 * difficulty of this file: `ROADMAP.md` is only PARTLY generated, so the unit
 * of comparison is a REGION, never the file.
 *
 * WHY THIS EXISTS: the phase index and the progress table were a parallel claim
 * about the phase directories rather than a rendering of them. On 2026-07-25 the
 * live file carried a hand-checked `- [x] **Phase 14: ...**` with no completion
 * stamp while the shipped status derivation reported that phase as executed and
 * not verified. The rule adopted in response: a governance file may claim
 * current state only if that claim is generated.
 *
 * HERMETIC BY CONTRACT (this is what makes `--check` meaningful):
 *   - no `child_process`, no `fs`, no clock, no network
 *   - callers pass text and already-derived records in
 *   - the renderers sort EXPLICITLY and never rely on input order, so a
 *     filesystem enumeration change cannot alter the rendered output
 *   - this module never imports the current-milestone extractor in
 *     `roadmap-parser`, which is the function that reads the state file.
 *     Importing it would close the D3c cycle: roadmap scoping already reads
 *     the state file, so a generated roadmap region that read it back would
 *     make both files unrepairable. A negative grep over this source is an
 *     acceptance criterion of the plan that introduced it.
 *
 * FAIL LOUD: a malformed region returns `{ok:false, code}` carrying the file,
 * the 1-based line and the offending line, and is NEVER silently overwritten.
 * Silently overwriting is how a generator eats a human's work and teaches
 * everyone to distrust it.
 *
 * THE REGION CONTRACT, stated once and applied to both regions. A region opens
 * at its own VISIBLE generated-notice blockquote and closes at the next level 2
 * heading or at end of file. Which region a notice opens is decided by the
 * heading it sits under: `## Phases` opens the phase index, `## Progress` opens
 * the progress section, anything else is `E_ROADMAP_REGION_ORPHAN`. The notice
 * is visible prose rather than a hidden marker, per D2: a hidden label splits
 * machine truth from human truth inside one file and lets the label be bumped
 * while the prose rots.
 *
 * CARRY THE LABELS, DERIVE THE STATE. A name, a tag and a description are
 * LABELS, and a wrong label is a naming error rather than a claim about what is
 * currently true, so they are carried forward from the prior committed region.
 * The checkbox, the plans column, the status column and whether a completion
 * date is rendered at all are current-state claims, and every one of them is
 * derived on every run. The date is the one carried value that IS a
 * current-state claim, so it is anchored: it renders only for an entry whose
 * derived status is the complete status, which makes the carry self-healing
 * rather than sticky.
 *
 * ADR-457 build-at-publish: compiles to ferrox-core/bin/lib/roadmap-index.cjs.
 */
// eslint-disable-next-line @typescript-eslint/no-require-imports -- milestone-manifest.cjs is an export= CommonJS module
const milestoneManifest = require("./milestone-manifest.cjs");
// eslint-disable-next-line @typescript-eslint/no-require-imports -- governance-manifest.cjs is an export= CommonJS module
const governanceManifest = require("./governance-manifest.cjs");
// eslint-disable-next-line @typescript-eslint/no-require-imports -- phase-id.cjs is an export= CommonJS module
const phaseIdMod = require("./phase-id.cjs");
const markdown_sectionizer_cjs_1 = require("./markdown-sectionizer.cjs");
const { comparePhaseNum } = phaseIdMod;
// ─── the vocabulary ──────────────────────────────────────────────────────────
const PHASES_HEADING = 'Phases';
const PROGRESS_HEADING = 'Progress';
const PHASE_DETAILS_HEADING = 'Phase Details';
/** The first bytes of every generated notice. Visible prose, never a marker. */
const NOTICE_SENTINEL = '> GENERATED by `scripts/gen-roadmap-index.cjs`';
/** The status value that makes an entry complete. From `determinePhaseStatus`. */
const COMPLETE_STATUS = 'Complete';
/** The 4 canonical progress columns, in canonical order. */
const PROGRESS_COLUMNS = ['Phase', 'Plans Complete', 'Status', 'Completed'];
const PROGRESS_HEADER_ROW = '| Phase | Plans Complete | Status | Completed |';
const PROGRESS_DELIMITER_ROW = '|-------|----------------|--------|-----------|';
const EXECUTION_ORDER_LABEL = '**Execution Order:**';
const EXECUTION_ORDER_PREFIX = 'Phases execute in numeric order: ';
const EXECUTION_ORDER_SEPARATOR = ' → ';
const DATE_SHAPE = /^\d{4}-\d{2}-\d{2}$/;
const INDEX_LINE_SHAPE = /^-\s*\[[ xX]\]\s*\*\*Phase\s/;
const TABLE_LINE_SHAPE = /^\|.*\|$/;
const FIX_COMMAND = 'node scripts/gen-roadmap-index.cjs --write';
const PHASES_NOTICE_LINES = [
    NOTICE_SENTINEL + ' from the phase directories on disk',
    '> and the `### Phase N:` headings under `## Phase Details`. Do not edit by hand:',
    '> `--check` runs inside `lint:generated-sync`, so an edit here fails `lint:ci`. To',
    '> change an entry, edit its phase detail section and run',
    '> `' + FIX_COMMAND + '`.',
];
const PROGRESS_NOTICE_LINES = [
    NOTICE_SENTINEL + ' from the phase directories on disk',
    '> and the `### Phase N:` headings under `## Phase Details`. Do not edit by hand:',
    '> `--check` runs inside `lint:generated-sync`, so an edit here fails `lint:ci`. To',
    '> move a row, add a plan or a summary to that phase directory and run',
    '> `' + FIX_COMMAND + '`.',
];
function err(file, code, message, extra) {
    const e = { ok: false, code, message, file };
    if (extra && typeof extra.line === 'number')
        e.line = extra.line;
    if (extra && typeof extra.text === 'string')
        e.text = extra.text;
    return e;
}
// ─── line arithmetic ─────────────────────────────────────────────────────────
/**
 * Split into lines while keeping each line's byte offset in the ORIGINAL text,
 * so a region can be spliced back without re-deriving positions. CRLF tolerant
 * (`local/no-crlf-fragile-split`): the carriage return is dropped from the line
 * text but still counted in the offsets.
 */
function splitLines(text) {
    const lines = [];
    const offsets = [];
    let start = 0;
    for (let i = 0; i <= text.length; i++) {
        if (i === text.length || text.charAt(i) === '\n') {
            let line = text.slice(start, i);
            if (line.endsWith('\r'))
                line = line.slice(0, -1);
            lines.push(line);
            offsets.push(start);
            start = i + 1;
            if (i === text.length)
                break;
        }
    }
    return { lines, offsets };
}
/** Heading tokens of level 1 or 2, which are the only region boundaries. */
function topHeadings(text) {
    return (0, markdown_sectionizer_cjs_1.tokenizeHeadings)(text)
        .filter((h) => h.level <= 2)
        .map((h) => ({ level: h.level, text: h.text, line: h.line }));
}
function headingKind(headingText) {
    const t = headingText.trim();
    if (t.toLowerCase() === PHASES_HEADING.toLowerCase())
        return 'phases';
    if (t.toLowerCase() === PROGRESS_HEADING.toLowerCase())
        return 'progress';
    return null;
}
function headingOf(kind) {
    return kind === 'phases' ? PHASES_HEADING : PROGRESS_HEADING;
}
// ─── the region locator ──────────────────────────────────────────────────────
/**
 * Locate both generated regions.
 *
 * When a notice is present the span runs from the notice line to the line
 * before the next level 2 heading. When it is absent the span is still returned
 * as a BOOTSTRAP anchor, so `--write` can establish the region on the first run,
 * and `E_ROADMAP_REGION_MISSING` is reported so `--check` fails.
 */
function locateRegions(text, filename) {
    const file = typeof filename === 'string' && filename !== '' ? filename : 'ROADMAP.md';
    const errors = [];
    const regions = {
        phases: null,
        progress: null,
    };
    if (typeof text !== 'string' || text === '') {
        errors.push(err(file, 'E_ROADMAP_REGION_MISSING', 'the roadmap is empty or not a string'));
        return { ok: false, regions, errors };
    }
    const { lines, offsets } = splitLines(text);
    const headings = topHeadings(text);
    const boundaryAfter = (line) => {
        for (const h of headings) {
            if (h.line > line) {
                return { endLine: h.line - 1, endOffset: offsets[h.line - 1] };
            }
        }
        return { endLine: lines.length, endOffset: text.length };
    };
    const headingBefore = (line) => {
        let found = null;
        for (const h of headings) {
            if (h.line < line)
                found = h;
            else
                break;
        }
        return found;
    };
    // 1. Every notice in the file, classified by the heading it sits under.
    for (let i = 0; i < lines.length; i++) {
        if (!lines[i].startsWith(NOTICE_SENTINEL))
            continue;
        const noticeLine = i + 1;
        const owner = headingBefore(noticeLine);
        const kind = owner && owner.level === 2 ? headingKind(owner.text) : null;
        if (kind === null) {
            errors.push(err(file, 'E_ROADMAP_REGION_ORPHAN', `a generated notice sits under \`${owner ? '## ' + owner.text : 'no heading'}\`, `
                + `which owns no generated region. Move it under \`## ${PHASES_HEADING}\` or `
                + `\`## ${PROGRESS_HEADING}\`, or delete it.`, { line: noticeLine, text: lines[i] }));
            continue;
        }
        if (regions[kind] !== null) {
            errors.push(err(file, 'E_ROADMAP_REGION_DUPLICATE', `\`## ${headingOf(kind)}\` carries more than 1 generated notice, so the region has `
                + `no single boundary. Delete the extra notice and run:\n  ${FIX_COMMAND}`, { line: noticeLine, text: lines[i] }));
            continue;
        }
        const bound = boundaryAfter(noticeLine);
        regions[kind] = {
            kind,
            heading: headingOf(kind),
            present: true,
            startLine: noticeLine,
            endLine: bound.endLine,
            startOffset: offsets[i],
            endOffset: bound.endOffset,
        };
    }
    // 2. A missing notice is an error, and also a bootstrap anchor for `--write`.
    for (const kind of ['phases', 'progress']) {
        if (regions[kind] !== null)
            continue;
        const heading = headings.find((h) => h.level === 2 && headingKind(h.text) === kind);
        if (heading === undefined) {
            errors.push(err(file, 'E_ROADMAP_REGION_MISSING', `\`## ${headingOf(kind)}\` is missing, so its generated region has nowhere to live. `
                + `Add the heading and run:\n  ${FIX_COMMAND}`));
            continue;
        }
        const bound = boundaryAfter(heading.line);
        // The phase index anchors at the first existing entry so the hand-written
        // block above it (the phase numbering note) is preserved byte for byte and
        // is never rendered. The progress section anchors immediately after its
        // heading, because it carries no hand-written preamble.
        let anchorLine = heading.line + 1;
        if (kind === 'phases') {
            let firstEntry = -1;
            for (let i = heading.line; i < bound.endLine; i++) {
                if (INDEX_LINE_SHAPE.test(lines[i])) {
                    firstEntry = i + 1;
                    break;
                }
            }
            anchorLine = firstEntry === -1 ? bound.endLine + 1 : firstEntry;
        }
        if (anchorLine > lines.length)
            anchorLine = lines.length;
        errors.push(err(file, 'E_ROADMAP_REGION_MISSING', `\`## ${headingOf(kind)}\` carries no generated notice, so its region is unbounded and `
            + `unchecked. Run:\n  ${FIX_COMMAND}`, { line: anchorLine }));
        regions[kind] = {
            kind,
            heading: headingOf(kind),
            present: false,
            startLine: anchorLine,
            endLine: bound.endLine,
            startOffset: offsets[anchorLine - 1],
            endOffset: bound.endOffset,
        };
    }
    // 3. Nothing but the notice and that region's own content shape may live
    //    inside a region. A foreign line is a loud failure, never an overwrite.
    for (const kind of ['phases', 'progress']) {
        const span = regions[kind];
        if (span === null)
            continue;
        const code = kind === 'phases' ? 'E_ROADMAP_INDEX_INTERLEAVED' : 'E_ROADMAP_PROGRESS_INTERLEAVED';
        let inNotice = span.present;
        for (let i = span.startLine - 1; i < span.endLine && i < lines.length; i++) {
            const line = lines[i];
            if (inNotice) {
                if (line.startsWith('>'))
                    continue;
                inNotice = false;
            }
            if (line.trim() === '')
                continue;
            const allowed = kind === 'phases'
                ? INDEX_LINE_SHAPE.test(line)
                : line.trim() === EXECUTION_ORDER_LABEL
                    || line.startsWith(EXECUTION_ORDER_PREFIX)
                    || TABLE_LINE_SHAPE.test(line.trim());
            if (allowed)
                continue;
            errors.push(err(file, code, `${file}:${i + 1} sits inside the generated \`## ${span.heading}\` region but is not `
                + `part of it: ${JSON.stringify(line)}. The generator refuses to overwrite it. Move `
                + `the line outside the region, then run:\n  ${FIX_COMMAND}`, { line: i + 1, text: line }));
        }
    }
    return { ok: errors.length === 0, regions, errors };
}
// ─── the phase list ──────────────────────────────────────────────────────────
const DETAIL_HEADING_SHAPE = /^Phase\s+(\d+[A-Za-z]?(?:\.\d+)*)\s*(?:\(([^)\n]{0,200})\))?\s*:\s*(.+)$/i;
const TRAILING_TAG_SHAPE = /^(.*?)\s*\(([^)\n]{0,200})\)\s*$/;
/**
 * The phase list, built from the `### Phase N:` headings under
 * `## Phase Details`. Headings folded inside a `<details>` block are ignored, so
 * a shipped milestone archived into the file cannot inject entries. The
 * `<details open>` form marks the ACTIVE milestone and is preserved (#557).
 *
 * Returns skeleton entries: number, name and the heading's own tag. The plan
 * counts, the status and the completion date are supplied by the impure scan.
 */
function collectPhaseEntries(text, filename) {
    const file = typeof filename === 'string' && filename !== '' ? filename : 'ROADMAP.md';
    const errors = [];
    const entries = [];
    if (typeof text !== 'string' || text === '') {
        return { ok: true, entries, errors };
    }
    const visible = (0, markdown_sectionizer_cjs_1.stripTaggedBlocks)(text, 'details');
    const headings = (0, markdown_sectionizer_cjs_1.tokenizeHeadings)(visible);
    const seen = new Map();
    let inDetails = false;
    for (const h of headings) {
        if (h.level <= 2) {
            inDetails = h.text.trim().toLowerCase() === PHASE_DETAILS_HEADING.toLowerCase();
            continue;
        }
        if (!inDetails)
            continue;
        const m = DETAIL_HEADING_SHAPE.exec(h.text.trim());
        if (m === null)
            continue;
        const number = m[1];
        let parenthetical = m[2] === undefined ? '' : `(${m[2]})`;
        let name = m[3].trim();
        if (parenthetical === '') {
            const trailing = TRAILING_TAG_SHAPE.exec(name);
            if (trailing !== null) {
                name = trailing[1].trim();
                parenthetical = `(${trailing[2]})`;
            }
        }
        const prior = seen.get(number);
        if (prior !== undefined) {
            errors.push(err(file, 'E_ROADMAP_DUPLICATE_PHASE', `2 phase detail headings claim phase ${number}: ${JSON.stringify(prior)} and `
                + `${JSON.stringify(name)}. One phase number, one heading.`, { line: h.line, text: h.text }));
            continue;
        }
        seen.set(number, name);
        entries.push({
            number,
            name,
            parenthetical,
            description: '',
            planCount: 0,
            summaryCount: 0,
            status: '',
            completedDate: '',
        });
    }
    return { ok: errors.length === 0, entries: sortEntries(entries), errors };
}
/** Explicit decimal-aware sort. Input order is never consulted. */
function sortEntries(entries) {
    return entries.slice().sort((a, b) => comparePhaseNum(a.number, b.number));
}
// ─── the renderers ───────────────────────────────────────────────────────────
/**
 * Render the phase index region, notice included.
 *
 * The line shape is `- [ ] **Phase N: Name**` with an optional trailing
 * parenthetical, because 3 readers in `src/phase.cts` depend on it and 8 more
 * consumers outside that file share the same shape. The completion
 * parenthetical goes at the END of the line, which is where the retired
 * `updateBullet` flip put it, so a line the SDK used to produce and a line this
 * renderer produces have the same shape.
 */
function renderPhaseIndex(entries) {
    const lines = PHASES_NOTICE_LINES.slice();
    lines.push('');
    for (const e of sortEntries(entries)) {
        const complete = e.status === COMPLETE_STATUS;
        let line = `- [${complete ? 'x' : ' '}] **Phase ${e.number}: ${e.name}**`;
        if (e.parenthetical)
            line += ` ${e.parenthetical}`;
        if (e.description)
            line += ` - ${e.description}`;
        // The date is a current-state claim, so it is anchored to the derived
        // status. An entry that regresses out of complete loses its date on the
        // next render, which is the same self-heal rule the retired table writer
        // applied when it cleared the cell for a phase that was not complete.
        if (complete && DATE_SHAPE.test(e.completedDate))
            line += ` (completed ${e.completedDate})`;
        lines.push(line);
    }
    return lines.join('\n');
}
/**
 * Render the progress region, notice included. The header carries the 4
 * canonical column names in the canonical order, because
 * `deriveProgressFromRoadmap` reads the table by column NAME.
 */
function renderProgressSection(entries) {
    const sorted = sortEntries(entries);
    const lines = PROGRESS_NOTICE_LINES.slice();
    lines.push('');
    lines.push(EXECUTION_ORDER_LABEL);
    lines.push(EXECUTION_ORDER_PREFIX + sorted.map((e) => e.number).join(EXECUTION_ORDER_SEPARATOR));
    lines.push('');
    lines.push(PROGRESS_HEADER_ROW);
    lines.push(PROGRESS_DELIMITER_ROW);
    for (const e of sorted) {
        // A period is added only when the number carries none of its own, so the
        // integer row pattern `^N\.?(?:\s|$)` selects the integer row and rejects a
        // decimal row that shares its leading digits.
        const label = e.number.includes('.') ? `${e.number} ${e.name}` : `${e.number}. ${e.name}`;
        const first = e.parenthetical ? `${label} ${e.parenthetical}` : label;
        const plans = e.planCount === 0 ? '0/TBD' : `${e.summaryCount}/${e.planCount}`;
        const complete = e.status === COMPLETE_STATUS;
        const done = complete && DATE_SHAPE.test(e.completedDate) ? e.completedDate : '-';
        lines.push(`| ${first} | ${plans} | ${e.status} | ${done} |`);
    }
    return lines.join('\n');
}
// ─── the carried values ──────────────────────────────────────────────────────
const CARRIED_ENTRY_SHAPE = /^-\s*\[[ xX]\]\s*\*\*Phase\s+(\d+[A-Za-z]?(?:\.\d+)*):\s*([^*]*)\*\*\s*(.*)$/;
const COMPLETION_TAIL_SHAPE = /\s*\(completed\s+\d{4}-\d{2}-\d{2}\)\s*$/;
/**
 * The labels a prior committed index region carried, per phase number.
 *
 * A name, a tag and a description are labels rather than claims, so they
 * survive a regeneration. The completion parenthetical is stripped here because
 * it is state, not a label, and it is re-derived on every render.
 */
function extractCarriedLabels(regionText) {
    const out = {};
    if (typeof regionText !== 'string' || regionText === '')
        return out;
    for (const raw of regionText.split(/\r?\n/)) {
        const m = CARRIED_ENTRY_SHAPE.exec(raw);
        if (m === null)
            continue;
        const number = m[1];
        let rest = m[3].replace(COMPLETION_TAIL_SHAPE, '').trim();
        let parenthetical = '';
        if (rest.startsWith('(')) {
            const close = rest.indexOf(')');
            if (close !== -1) {
                parenthetical = rest.slice(0, close + 1);
                rest = rest.slice(close + 1).trim();
            }
        }
        let description = rest;
        if (description.startsWith('-'))
            description = description.slice(1).trim();
        out[number] = { parenthetical, description };
    }
    return out;
}
const CARRIED_ROW_PHASE_SHAPE = /^(\d+[A-Za-z]?(?:\.\d+)*)\.?(?:\s|$)/;
/**
 * The completion dates a prior committed progress region carried, per phase
 * number. Only a value matching the date shape survives; anything else is
 * discarded, which is the same self-healing rule the retired table writer
 * already applied.
 */
function extractCarriedDates(regionText) {
    const out = {};
    if (typeof regionText !== 'string' || regionText === '')
        return out;
    for (const raw of regionText.split(/\r?\n/)) {
        const line = raw.trim();
        if (!TABLE_LINE_SHAPE.test(line))
            continue;
        const cells = line.slice(1, -1).split('|').map((c) => c.trim());
        if (cells.length < PROGRESS_COLUMNS.length)
            continue;
        const m = CARRIED_ROW_PHASE_SHAPE.exec(cells[0]);
        if (m === null)
            continue;
        const date = cells[PROGRESS_COLUMNS.length - 1];
        if (!DATE_SHAPE.test(date))
            continue;
        out[m[1]] = date;
    }
    return out;
}
// ─── the scope assertion ─────────────────────────────────────────────────────
/**
 * The roadmap's visible scope declaration must name the single `lifecycle:
 * active` milestone.
 *
 * D1: resolution goes through the shipped `activeMilestone` resolver and never
 * by newest version, because resolving by max version turns `lint:ci` red the
 * moment anyone drafts a future milestone, and an unattended fleet cannot
 * self-resolve that gate. The resolver returns null for BOTH zero active and
 * more than 1 active, so this caller owns 2 distinct messages.
 *
 * The declaration itself is parsed by the shipped `parseScopeDeclaration` from
 * `governance-manifest`, so this phase does not ship a second parser for the
 * one line it already owns.
 */
function assertScope(text, groups, filename) {
    const file = typeof filename === 'string' && filename !== '' ? filename : 'ROADMAP.md';
    const list = Array.isArray(groups) ? groups : [];
    const active = milestoneManifest.activeMilestone(list);
    if (active === null) {
        const count = list.filter((g) => g && g.lifecycle === 'active').length;
        if (count === 0) {
            return err(file, 'E_ROADMAP_NO_ACTIVE_MILESTONE', 'no .planning milestone artifact carries `lifecycle: active`, so the roadmap scope '
                + 'cannot be checked. Run:\n  set `lifecycle: active` in the frontmatter of the '
                + 'intended .planning/MILESTONE-v*.md');
        }
        return err(file, 'E_ROADMAP_MULTIPLE_ACTIVE_MILESTONES', `${count} milestone artifacts carry \`lifecycle: active\`, and exactly 1 may. Run:\n`
            + '  node scripts/gen-milestones.cjs --check');
    }
    const declared = governanceManifest.parseScopeDeclaration(text, file);
    if (declared.ok === false) {
        const d = declared;
        return err(file, 'E_ROADMAP_SCOPE_UNREADABLE', d.message, { line: d.line, text: d.text });
    }
    const version = declared.version;
    if (version !== active.milestone) {
        return err(file, 'E_ROADMAP_SCOPE_MISMATCH', `the roadmap scope declaration names milestone v${version} but the single active `
            + `milestone is v${active.milestone}. Fix whichever one is wrong.`, { line: declared.line });
    }
    return null;
}
// ─── splicing ────────────────────────────────────────────────────────────────
/**
 * Replace one region's bytes and preserve every byte outside it.
 *
 * Exactly 1 blank line is kept before the region and before whatever follows
 * it, so a first write against a file that never carried a notice lands the
 * same bytes as every later write. That is what makes the write idempotent.
 */
function spliceRegion(text, span, rendered) {
    const before = text.slice(0, span.startOffset).replace(/\n*$/, '\n\n');
    const after = text.slice(span.endOffset).replace(/^\n*/, '');
    if (after === '')
        return before + rendered + '\n';
    return before + rendered + '\n\n' + after;
}
/**
 * Splice both rendered regions back. Later region first, so an earlier region's
 * offsets are not shifted by a length-changing replacement below it.
 */
function applyRegions(text, regions, rendered) {
    let out = text;
    const ordered = [regions.phases, regions.progress]
        .filter((s) => s !== null)
        .sort((a, b) => b.startOffset - a.startOffset);
    for (const span of ordered) {
        out = spliceRegion(out, span, rendered[span.kind]);
    }
    return out;
}
/** The region's committed bytes, for a byte compare that never leaves it. */
function regionText(text, span) {
    return text.slice(span.startOffset, span.endOffset);
}
